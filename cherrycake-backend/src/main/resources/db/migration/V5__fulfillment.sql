-- CC-25: pickup points, delivery zones, time slots and dining tables (bonus stage 4) with seed data.
-- CC-38: orders remember how they are received (pickup or delivery), where, and in which time slot.
-- delivery_fee is in conventional units (CU) like all catalog prices; the API converts it with regions.exchange_rate.
-- Six decimals keep fees set in UZS exact: 25 000 UZS / 3000 = 8.333333 CU, which converts back to 25 000.00 UZS.

CREATE TABLE pickup_points (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    region_id     BIGINT       NOT NULL,
    name          VARCHAR(150) NOT NULL,
    address       VARCHAR(255) NOT NULL,
    opening_hours VARCHAR(50)  NOT NULL,
    is_available  BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT fk_pickup_points_region FOREIGN KEY (region_id) REFERENCES regions (id),
    CONSTRAINT uq_pickup_points_region_name UNIQUE (region_id, name)
);

CREATE TABLE delivery_zones (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    region_id    BIGINT         NOT NULL,
    name         VARCHAR(100)   NOT NULL,
    delivery_fee NUMERIC(12, 6) NOT NULL,
    is_available BOOLEAN        NOT NULL DEFAULT TRUE,
    CONSTRAINT fk_delivery_zones_region FOREIGN KEY (region_id) REFERENCES regions (id),
    CONSTRAINT uq_delivery_zones_region_name UNIQUE (region_id, name),
    CONSTRAINT ck_delivery_zones_fee CHECK (delivery_fee >= 0)
);

-- A slot repeats every day; its capacity is the number of orders it accepts on one date.
CREATE TABLE time_slots (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    start_time   TIME    NOT NULL,
    end_time     TIME    NOT NULL,
    capacity     INTEGER NOT NULL,
    is_available BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_time_slots_start UNIQUE (start_time),
    CONSTRAINT ck_time_slots_range CHECK (end_time > start_time),
    CONSTRAINT ck_time_slots_capacity CHECK (capacity >= 0)
);

CREATE TABLE dining_tables (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pickup_point_id BIGINT  NOT NULL,
    table_number    INTEGER NOT NULL,
    seats           INTEGER NOT NULL,
    is_available    BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT fk_dining_tables_pickup_point FOREIGN KEY (pickup_point_id) REFERENCES pickup_points (id),
    CONSTRAINT uq_dining_tables_number UNIQUE (pickup_point_id, table_number),
    CONSTRAINT ck_dining_tables_seats CHECK (seats >= 1)
);

