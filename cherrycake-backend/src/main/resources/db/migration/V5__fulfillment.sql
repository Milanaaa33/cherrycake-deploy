ALTER TABLE orders ADD CONSTRAINT fk_orders_delivery_zone FOREIGN KEY (delivery_zone_id) REFERENCES delivery_zones (id);
ALTER TABLE orders ADD CONSTRAINT fk_orders_time_slot FOREIGN KEY (time_slot_id) REFERENCES time_slots (id);
-- Orders created before CC-38 keep all four columns empty.
ALTER TABLE orders ADD CONSTRAINT ck_orders_fulfillment CHECK (
    (fulfillment_type IS NULL AND pickup_point_id IS NULL AND delivery_zone_id IS NULL AND time_slot_id IS NULL)
    OR (fulfillment_type = 'PICKUP' AND pickup_point_id IS NOT NULL AND delivery_zone_id IS NULL
        AND time_slot_id IS NOT NULL)
    OR (fulfillment_type = 'DELIVERY' AND delivery_zone_id IS NOT NULL AND pickup_point_id IS NULL
        AND time_slot_id IS NOT NULL));

-- Counting the orders of one slot on one date is the capacity check.
CREATE INDEX idx_orders_time_slot_date ON orders (time_slot_id, order_date);

