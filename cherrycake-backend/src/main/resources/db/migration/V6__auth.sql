-- Passwordless sign-in by email code: one-time codes and sessions.
-- Only SHA-256 hashes are stored: the code itself is sent by email, the session token is kept by the browser.
CREATE TABLE auth_codes (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email       VARCHAR(150) NOT NULL,
    code_hash   VARCHAR(64)  NOT NULL,
    expires_at  TIMESTAMP    NOT NULL,
    attempts    INTEGER      NOT NULL DEFAULT 0,
    created_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_auth_codes_email_created_at ON auth_codes (email, created_at);

CREATE TABLE auth_sessions (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_hash  VARCHAR(64)  NOT NULL,
    email       VARCHAR(150) NOT NULL,
    expires_at  TIMESTAMP    NOT NULL,
    created_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_auth_sessions_token_hash UNIQUE (token_hash)
);
