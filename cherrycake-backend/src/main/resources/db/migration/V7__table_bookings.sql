-- Real table reservations, separate from product orders.
CREATE TABLE table_bookings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_number VARCHAR(50) NOT NULL UNIQUE,
    pickup_point_id BIGINT NOT NULL REFERENCES pickup_points(id),
    dining_table_id BIGINT NOT NULL REFERENCES dining_tables(id),
    booking_date DATE NOT NULL,
    time_slot_id BIGINT NOT NULL REFERENCES time_slots(id),
    guests_count INTEGER NOT NULL CHECK (guests_count BETWEEN 1 AND 12),
    customer_name VARCHAR(150) NOT NULL,
    phone VARCHAR(50) NOT NULL,
    email VARCHAR(150) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_table_booking UNIQUE (dining_table_id, booking_date, time_slot_id)
);
CREATE INDEX idx_table_bookings_date_slot ON table_bookings(booking_date, time_slot_id);
