-- Table Bookings schema for cafe reservations (CC-39)
CREATE TABLE IF NOT EXISTS table_bookings (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_number VARCHAR(50)  NOT NULL UNIQUE,
    email          VARCHAR(150),
    table_number   INT          NOT NULL,
    guests_count   INT          NOT NULL DEFAULT 2,
    booking_time   TIMESTAMP    NOT NULL,
    status         VARCHAR(30)  NOT NULL DEFAULT 'CONFIRMED',
    customer_name  VARCHAR(150) NOT NULL,
    customer_phone VARCHAR(50)  NOT NULL,
    notes          TEXT,
    created_at     TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_table_bookings_time ON table_bookings (booking_time);
CREATE INDEX IF NOT EXISTS idx_table_bookings_table_time ON table_bookings (table_number, booking_time);
