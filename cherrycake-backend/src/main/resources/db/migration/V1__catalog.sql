-- CC-5: catalog schema (regions, categories, products, prices, modifiers, discounts).
-- Money is NUMERIC(12,2), rates are NUMERIC(5,4) stored as a fraction (0.15 = 15 %).
-- Prices, modifier deltas and discount thresholds are in conventional units (CU).
-- regions.exchange_rate says how much local currency one CU is worth (UZB: 3000 = 1 CU costs 3000 UZS).

CREATE TABLE regions (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code            VARCHAR(3)    NOT NULL,
    name            VARCHAR(100)  NOT NULL,
    currency_code   VARCHAR(3)    NOT NULL,
    currency_symbol VARCHAR(10)   NOT NULL,
    vat_rate        NUMERIC(5, 4) NOT NULL,
    exchange_rate   NUMERIC(12, 4) NOT NULL,
    CONSTRAINT uq_regions_code UNIQUE (code),
    CONSTRAINT ck_regions_vat_rate CHECK (vat_rate >= 0 AND vat_rate < 1),
    CONSTRAINT ck_regions_exchange_rate CHECK (exchange_rate > 0)
);

CREATE TABLE categories (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(100) NOT NULL,
    sort_order INTEGER      NOT NULL DEFAULT 0
);

CREATE TABLE products (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id BIGINT        NOT NULL,
    name        VARCHAR(150)  NOT NULL,
    description VARCHAR(1000),
    photo_url   VARCHAR(500),
    CONSTRAINT fk_products_category FOREIGN KEY (category_id) REFERENCES categories (id)
);

CREATE INDEX idx_products_category_id ON products (category_id);

CREATE TABLE regional_prices (
    product_id BIGINT         NOT NULL,
    region_id  BIGINT         NOT NULL,
    price      NUMERIC(12, 2) NOT NULL,
    in_stock   BOOLEAN        NOT NULL DEFAULT TRUE,
    CONSTRAINT pk_regional_prices PRIMARY KEY (product_id, region_id),
    CONSTRAINT fk_regional_prices_product FOREIGN KEY (product_id) REFERENCES products (id) ON DELETE CASCADE,
    CONSTRAINT fk_regional_prices_region FOREIGN KEY (region_id) REFERENCES regions (id),
    CONSTRAINT ck_regional_prices_price CHECK (price >= 0)
);

CREATE INDEX idx_regional_prices_region_id ON regional_prices (region_id);

CREATE TABLE modifier_groups (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id  BIGINT       NOT NULL,
    name        VARCHAR(100) NOT NULL,
    type        VARCHAR(10)  NOT NULL,
    is_required BOOLEAN      NOT NULL DEFAULT FALSE,
    CONSTRAINT fk_modifier_groups_product FOREIGN KEY (product_id) REFERENCES products (id) ON DELETE CASCADE,
    CONSTRAINT ck_modifier_groups_type CHECK (type IN ('SINGLE', 'MULTI'))
);

CREATE INDEX idx_modifier_groups_product_id ON modifier_groups (product_id);

CREATE TABLE modifiers (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id BIGINT       NOT NULL,
    name     VARCHAR(100) NOT NULL,
    CONSTRAINT fk_modifiers_group FOREIGN KEY (group_id) REFERENCES modifier_groups (id) ON DELETE CASCADE
);

CREATE INDEX idx_modifiers_group_id ON modifiers (group_id);

CREATE TABLE modifier_regional_prices (
    modifier_id BIGINT         NOT NULL,
    region_id   BIGINT         NOT NULL,
    price_delta NUMERIC(12, 2) NOT NULL DEFAULT 0,
    CONSTRAINT pk_modifier_regional_prices PRIMARY KEY (modifier_id, region_id),
    CONSTRAINT fk_modifier_regional_prices_modifier FOREIGN KEY (modifier_id) REFERENCES modifiers (id) ON DELETE CASCADE,
    CONSTRAINT fk_modifier_regional_prices_region FOREIGN KEY (region_id) REFERENCES regions (id),
    CONSTRAINT ck_modifier_regional_prices_delta CHECK (price_delta >= 0)
);

CREATE INDEX idx_modifier_regional_prices_region_id ON modifier_regional_prices (region_id);

CREATE TABLE discount_rules (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    threshold NUMERIC(12, 2) NOT NULL,
    rate      NUMERIC(5, 4)  NOT NULL,
    CONSTRAINT uq_discount_rules_threshold UNIQUE (threshold),
    CONSTRAINT ck_discount_rules_threshold CHECK (threshold >= 0),
    CONSTRAINT ck_discount_rules_rate CHECK (rate >= 0 AND rate < 1)
);
