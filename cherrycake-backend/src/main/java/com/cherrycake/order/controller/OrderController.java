package com.cherrycake.order.controller;

import com.cherrycake.auth.service.AuthService;
import com.cherrycake.common.dto.ErrorResponse;
import com.cherrycake.order.dto.ClaimOrdersRequest;
import com.cherrycake.order.dto.CreateOrderRequest;
import com.cherrycake.order.dto.OrderResponse;
import com.cherrycake.order.service.OrderService;
import io.swagger.v3.oas.annotations.Operation;
import io.swagger.v3.oas.annotations.Parameter;
import io.swagger.v3.oas.annotations.media.Content;
import io.swagger.v3.oas.annotations.media.Schema;
import io.swagger.v3.oas.annotations.responses.ApiResponse;
import io.swagger.v3.oas.annotations.tags.Tag;
import jakarta.validation.Valid;
import org.springframework.http.HttpStatus;
import java.util.List;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.RequestBody;
import org.springframework.web.bind.annotation.RequestHeader;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.ResponseStatus;
import org.springframework.web.bind.annotation.RestController;

@RestController
@RequestMapping("/api/orders")
@Tag(name = "Orders", description = "Guest checkout and order creation with server-side price recalculation")
public class OrderController {

    public static final String CLIENT_ID_HEADER = "X-Client-Id";

    private final OrderService orderService;
    private final AuthService authService;

    public OrderController(OrderService orderService, AuthService authService) {
        this.orderService = orderService;
        this.authService = authService;
    }

    @PostMapping
    @ResponseStatus(HttpStatus.CREATED)
    @Operation(summary = "Create guest order, recalculate totals via BE1 calculator and persist order")
    @ApiResponse(responseCode = "201", description = "Order created")
    @ApiResponse(responseCode = "400", description = "Validation error (past date, invalid email, missing required modifiers)",
            content = @Content(schema = @Schema(implementation = ErrorResponse.class)))
    @ApiResponse(responseCode = "404", description = "Unknown region or product",
            content = @Content(schema = @Schema(implementation = ErrorResponse.class)))
    @ApiResponse(responseCode = "409", description = "Product out of stock in the selected region",
            content = @Content(schema = @Schema(implementation = ErrorResponse.class)))
    public OrderResponse createOrder(
            @Valid @RequestBody CreateOrderRequest request,
            @Parameter(description = "Anonymous browser id; when sent, the order appears in GET /api/orders/my",
                    example = "3f2b8c1e-6a4d-4e7b-9c1a-2d5f7a9b0c3e")
            @RequestHeader(value = CLIENT_ID_HEADER, required = false) String clientId) {
        return orderService.createOrder(request, clientId);
    }

    @GetMapping("/my")
    @Operation(summary = "Order history (personal account), newest first. "
            + "Signed in (Authorization: Bearer): all orders with the account email plus this browser's orders. "
            + "Not signed in: orders of this browser (X-Client-Id).")
    @ApiResponse(responseCode = "200", description = "Orders; empty list if there are none")
    @ApiResponse(responseCode = "400", description = "Not signed in and X-Client-Id header is missing or malformed",
            content = @Content(schema = @Schema(implementation = ErrorResponse.class)))
    @ApiResponse(responseCode = "401", description = "The Authorization token is invalid or expired",
            content = @Content(schema = @Schema(implementation = ErrorResponse.class)))
    public List<OrderResponse> getMyOrders(
            @Parameter(description = "Anonymous browser id generated by the frontend",
                    example = "3f2b8c1e-6a4d-4e7b-9c1a-2d5f7a9b0c3e")
            @RequestHeader(value = CLIENT_ID_HEADER, required = false) String clientId,
            @Parameter(description = "Session token from POST /api/auth/verify-code: Bearer <token>")
            @RequestHeader(value = "Authorization", required = false) String authorization) {
        String email = authorization == null || authorization.isBlank()
                ? null
                : authService.requireEmail(authorization);
        return orderService.getOrderHistory(clientId, email);
    }

    @PostMapping("/my/claim")
    @Operation(summary = "Add earlier orders (same email and phone, no owner yet) to the current browser's history")
    @ApiResponse(responseCode = "200", description = "Full order history of this browser after the update, newest first")
    @ApiResponse(responseCode = "400", description = "Invalid email/phone or X-Client-Id header missing or malformed",
            content = @Content(schema = @Schema(implementation = ErrorResponse.class)))
    public List<OrderResponse> claimEarlierOrders(
            @Valid @RequestBody ClaimOrdersRequest request,
            @Parameter(description = "Anonymous browser id generated by the frontend",
                    example = "3f2b8c1e-6a4d-4e7b-9c1a-2d5f7a9b0c3e")
            @RequestHeader(value = CLIENT_ID_HEADER, required = false) String clientId) {
        return orderService.claimEarlierOrders(clientId, request.email(), request.phone());
    }
}
